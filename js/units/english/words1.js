function parse() {
  const out = [];
  for (const [theme, t] of Object.entries(RAW)) {
    for (const line of t.list.trim().split('\n')) {
      const [w, ja, pos] = line.split('|');
      out.push({ w, ja, pos: pos || t.pos, theme, grade: 1 });
    }
  }
  return out;
}
