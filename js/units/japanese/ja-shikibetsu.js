function genOf(type) {
  return (rng) => {
    const T = TYPES[type];
    const [s, ans] = rng.pick(T.list);
    return jaChoice(rng, {
      stem: `${T.title}: 次の【　】は、どれにあたる？\n${s}`,
      correct: ans,
      wrongs: T.cats.filter((c) => c !== ans).map((t) => ({ t, msg: `この【　】は「${ans}」。${T.tips[ans]}` })),
      n: T.cats.length,
      hint: Object.entries(T.tips).map(([k, v]) => `${k}: ${v}`).join('\n'),
      steps: [`→ ${ans}`, T.tips[ans]],
      verify: (t) => T.list.some(([x, a]) => x === s && a === t),
    });
  };
}
