  形容詞: '様子や性質を表し、言い切りの形が「〜い」で終わる。',
  形容動詞: '様子や性質を表し、言い切りの形が「〜だ」で終わる（「〜な」で名詞につながる）。',
  副詞: '活用せず、おもに用言（動詞・形容詞・形容動詞）をくわしくする。',
  連体詞: '活用せず、名詞（体言）だけをくわしくする（この・その・大きな・小さな・あらゆる など）。',
  接続詞: '文と文、語と語をつなぐ（だから・しかし・そして・または など）。',
  感動詞: '感動・呼びかけ・応答・あいさつを表し、ほかの語と関係なく使われる。',
  助詞: '付属語で活用しない。ほかの語について、関係を示したり意味をそえたりする。',
  助動詞: '付属語で活用する。ほかの語について、意味（打ち消し・受け身・推量など）をそえる。',
