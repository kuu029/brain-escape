// まちがえやすい組（選択肢にまぜる）
const NEAR = {
  名詞: ['動詞', '形容詞', '連体詞'], 動詞: ['形容詞', '助動詞', '名詞'], 形容詞: ['形容動詞', '動詞', '連体詞'], 形容動詞: ['形容詞', '連体詞', '副詞'],
  副詞: ['連体詞', '接続詞', '形容動詞'], 連体詞: ['形容動詞', '形容詞', '副詞'], 接続詞: ['副詞', '感動詞', '助詞'], 感動詞: ['接続詞', '副詞', '名詞'],
  助詞: ['助動詞', '接続詞', '名詞'], 助動詞: ['助詞', '動詞', '形容詞'],
};
const word = (s) => s.match(/【(.+?)】/)[1];

function genWhich(rng) {
  const [s, ans] = rng.pick(LIST);
  return jaChoice(rng, {
    stem: `次の文の【　】の語の品詞は？\n${s}`,
    correct: ans,
    wrongs: rng.shuffle(NEAR[ans]).map((t) => ({ t, msg: `「${word(s)}」は${ans}。${WHY[ans]}` })),
    hint: '自立語か付属語か → 活用するか → 言い切りの形は？ の順に考える。',
    steps: [`「${word(s)}」→ ${ans}`, WHY[ans]],
    verify: (t) => t === ans,
  });
}
// 「〇〇はどれ？」: 4つの語から、その品詞のものを選ぶ（ほかの3つはちがう品詞）
function genFind(rng) {
  const target = rng.pick(HINSHI);
  const right = rng.pick(LIST.filter(([, h]) => h === target));
  const ws = [];
  for (const h of others(rng, NEAR[target].concat(HINSHI), target, 9)) {
    if (ws.length === 3 || ws.some((w) => w.h === h)) continue;
    const pick = rng.pick(LIST.filter(([, x]) => x === h));
    ws.push({ h, s: pick[0] });
  }
  const fmt = (s) => s.replace(/【(.+?)】/, '［$1］');
  return jaChoice(rng, {
    stem: `次の文の［　］の語のうち、品詞が「${target}」のものは？`,
    correct: fmt(right[0]),
    wrongs: ws.map((w) => ({ t: fmt(w.s), msg: `「${word(w.s)}」は${w.h}。` })),
    hint: WHY[target],
    steps: [`「${word(right[0])}」が${target}。`, WHY[target]],
    verify: (t) => LIST.some(([s, h]) => fmt(s) === t && h === target),
  });
}

