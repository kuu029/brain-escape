const NEAR = { 五段活用: ['上一段活用', '下一段活用', 'サ行変格活用'], 上一段活用: ['五段活用', '下一段活用', 'カ行変格活用'], 下一段活用: ['上一段活用', '五段活用', 'サ行変格活用'], カ行変格活用: ['五段活用', '上一段活用', 'サ行変格活用'], サ行変格活用: ['五段活用', 'カ行変格活用', '下一段活用'] };
const why = (v, nai, k) => (k === 'カ行変格活用' ? '「来る」1語だけがカ行変格活用。' : k === 'サ行変格活用' ? '「する」「〜する」はサ行変格活用。' : `「ない」をつけると「${nai}」。ないの直前が${k === '五段活用' ? 'a段' : k === '上一段活用' ? 'i段' : 'e段'}の音 → ${k}。`);

function genKind(rng) {
  const [v, read, nai, k] = rng.pick(VERBS);
  return jaChoice(rng, {
    stem: `動詞「${v}」の活用の種類は？`,
    correct: k,
    wrongs: NEAR[k].map((t) => ({ t, msg: why(v, nai, k) })),
    hint: '「ない」をつけて、ないの直前の音を見る（a段・i段・e段）。来る・する は特別。',
    steps: [why(v, nai, k)],
    verify: (t) => t === kindOf(v, read, nai),
  });
}

// 活用形（五段活用の動詞）: 語幹 ＋ 行の音 ＋ 続く語
export const FORMS = ['未然形', '連用形', '終止形', '連体形', '仮定形', '命令形'];
const GODAN = [['書', 'かきくけこ'], ['読', 'まみむめも'], ['話', 'さしすせそ'], ['待', 'たちつてと'], ['遊', 'ばびぶべぼ'], ['走', 'らりるれろ'], ['泳', 'がぎぐげご'], ['歌', 'わいうえお']];
// [段の番号（0=a 1=i 2=u 3=e 4=o）, 続き, 活用形, 見分けのことば]
const USES = [
  [0, 'ない。', '未然形', '「ない」「う・よう」に続く → 未然形'], [4, 'う。', '未然形', '「う」に続く → 未然形'],
  [1, 'ます。', '連用形', '「ます」「た」に続く → 連用形'],
  [2, '。', '終止形', '言い切る → 終止形'], [2, 'とき、', '連体形', '名詞（体言）に続く → 連体形'],
  [3, 'ば、', '仮定形', '「ば」に続く → 仮定形'], [3, '！', '命令形', '命令して言い切る → 命令形'],
];
function genForm(rng) {
  const [stem, row] = rng.pick(GODAN);
  const [i, tail, form, note] = rng.pick(USES);
  let ch = [...row][i];
  if (stem === '歌' && i === 0) ch = 'わ'; // 歌わない（あ段は「わ」）
  return jaChoice(rng, {
    stem: `次の【　】の動詞の活用形は？\n【${stem}${ch}】${tail}`,
    correct: form,
    wrongs: rng.shuffle(FORMS.filter((f) => f !== form)).slice(0, 3).map((t) => ({ t, msg: note })),
    hint: '下に続く語で決まる。ない・う → 未然 ／ ます・た → 連用 ／ 言い切り → 終止 ／ 名詞 → 連体 ／ ば → 仮定 ／ 命令 → 命令',
    steps: [note],
    verify: (t) => t === form,
  });
}

