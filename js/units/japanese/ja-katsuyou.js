// 国語 第2段階: 動詞の活用（活用の種類・活用形）
//   活用の種類は「ない」をつけた形の、ないの直前の音で決まる（a段 → 五段、i段 → 上一段、e段 → 下一段）。来る → カ変、する → サ変
//   データ: [動詞, 読み, 「ない」をつけた形の読み, 種類（手で書いた答え。テストで規則と照らし合わせる）]
import { jaChoice } from './kit-ja.js';

export const KINDS = ['五段活用', '上一段活用', '下一段活用', 'カ行変格活用', 'サ行変格活用'];
const ROW = { a: 'あかさたなはまやらわがざだばぱ', i: 'いきしちにひみりぎじぢびぴ', e: 'えけせてねへめれげぜでべぺ' };
// 規則で種類を出す（データのまちがい探し用）
export function kindOf(verb, read, nai) {
  if (verb === '来る') return 'カ行変格活用';
  if (read === 'する' || read.endsWith('する')) return 'サ行変格活用';
  const ch = [...nai.replace(/ない$/, '')].pop();
  if (ROW.a.includes(ch)) return '五段活用';
  if (ROW.i.includes(ch)) return '上一段活用';
  if (ROW.e.includes(ch)) return '下一段活用';
  return null;
}
