// 問題の種類 → [表, 答えの候補]（テストからも使う）
export const LINKS = {
  region: [REGION_T, REGION], cont: [CONT_T, CONT], power: [POWER_T, POWER], unit: [UNIT_T, UNIT],
  'cause-soc': [CAUSE_SOC, CAUSE_SOC.map((r) => r[1])], 'cause-sci': [CAUSE_SCI, CAUSE_SCI.map((r) => r[1])],
  class: [CLASS_T, [...ANIMAL, ...PLANT]],
};
const ASK = {
  region: 'どの地方のこと？', cont: '世界のどの州のこと？', power: '三権のどこの仕事？', unit: '単位はどれ？',
  'cause-soc': 'その結果どうなった？', 'cause-sci': 'その結果どうなった？',
};

// 表から1つ出して、同じ表の別の答えをまぎれさせる
function linkQ(rng, key) {
  const [table, cats] = LINKS[key];
  const r = rng.pick(table);
  const pool = key === 'class' ? CLASS_OF(r[1]) : cats;
  const ask = key === 'class' ? (ANIMAL.includes(r[1]) ? 'どのなかま？（せきつい動物）' : 'どのなかま？（植物）') : ASK[key];
  const wrongs = rng.shuffle(pool.filter((c) => c !== r[1])).map((t) => ({ t }));
  return { type: key, stem: r[0], ask, ...textChoice(rng, r[1], wrongs), why: `${r[0]} → ${r[1]}\n${r[2]}`, check: { kind: 'flow-link', key, stem: r[0], ans: r[1] } };
}

// 社会 7種類・理科 4種類を同じくらいの割合で
const SOC_Q = [orderQ, firstQ, eraQ, (rng) => linkQ(rng, 'region'), (rng) => linkQ(rng, 'cont'), (rng) => linkQ(rng, 'power'), (rng) => linkQ(rng, 'cause-soc')];
const SCI_Q = [fieldQ, (rng) => linkQ(rng, 'unit'), (rng) => linkQ(rng, 'class'), (rng) => linkQ(rng, 'cause-sci')];
export function flowQuestion(subject, rng) {
  return rng.pick(subject === 'sci' ? SCI_Q : SOC_Q)(rng);
}
// 画面下の「順番ガイド」: 問題の種類ごとに、覚える土台になる並びだけを見せる（答えそのものは出さない）
export const ERA_LINE = ['縄文', '弥生', '古墳', '飛鳥', '奈良', '平安', '鎌倉', '室町', '安土桃山', '江戸', '明治', '大正', '昭和', '平成', '令和'];
const GUIDES = {
  era: { title: '時代の順番', steps: ERA_LINE },
  region: { title: '北から南へ', steps: REGION.map((r) => r.replace(/地方$/, '')) },
  power: { title: '三権分立', steps: ['国会（立法）', '内閣（行政）', '裁判所（司法）'], sep: '・' },
  animal: { title: 'せきつい動物（水中 → 陸上）', steps: ANIMAL },
  plant: { title: '植物（種子あり → 種子なし）', steps: PLANT },
};
export function flowGuide(p) {
  if (['order', 'first', 'era', 'cause-soc'].includes(p.type)) return GUIDES.era;
  if (p.type === 'region' || p.type === 'power') return GUIDES[p.type];
  if (p.type === 'class') return ANIMAL.includes(p.check.ans) ? GUIDES.animal : GUIDES.plant;
  return null;
}
