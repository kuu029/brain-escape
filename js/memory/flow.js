export const ERA = { 'soc-his1': '古代（縄文〜平安）', 'soc-his2': '中世（鎌倉〜戦国）', 'soc-his3': '近世（江戸）', 'soc-his4': '近代（幕末〜大正）', 'soc-his5': '現代（昭和〜）' };
